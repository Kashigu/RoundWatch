import math

def length(pts_str):
    pts = [list(map(float, p.split(','))) for p in pts_str.split()]
    l = 0.0
    for i in range(len(pts)-1):
        dx = pts[i+1][0] - pts[i][0]
        dy = pts[i+1][1] - pts[i][1]
        l += math.hypot(dx, dy)
    return l

